def test_worker_runs_source_ticks_on_their_own_thread() -> None:
    calls: list[str] = []
    run_forever(once=True, pass_fn=lambda: calls.append("pass"),
                sources_fn=lambda: calls.append("tick"))
    assert calls == ["pass", "tick"]

    stop, ticked = threading.Event(), threading.Event()
    t = threading.Thread(target=run_forever, kwargs={
        "stop": stop, "interval_min": 1440, "tick_min": 1, "pass_fn": lambda: None,
        "sources_fn": ticked.set})
    t.start()
    assert ticked.wait(5)  # while the 24 h curation wait is running
    stop.set()
    t.join(5)
    assert not t.is_alive()

    none: list[str] = []
    run_forever(once=True, pass_fn=lambda: none.append("pass"))  # tests' pass_fn: no tick
    assert none == ["pass"]


