def test_webhook_secret_is_shown_once_and_sealed(env: Env, repo: tuple[str, str]) -> None:  # noqa: F811
    url, _ = repo
    sid = git_source(env, url)
    assert env.post(f"/v1/sources/{sid}/webhook", {}, role="curator").status_code == 403
    r = env.post(f"/v1/sources/{sid}/webhook", {})
    assert r.status_code == 200, r.text
    body = r.json()
    secret = body["secret"]
    assert body["url"] == f"http://localhost:8080/v1/hooks/sources/{sid}" and not body["rotated"]
    stored = env.src("auto").config["webhook_secret"]
    assert is_sealed(stored) and secret not in stored

    listed = env.client.get("/v1/sources", headers=env.h()).text
    assert secret not in listed
    [row] = [x for x in json.loads(listed) if x["id"] == sid]
    assert row["config"]["webhook_secret"] == "***" and row["webhook_url"] == body["url"]

    # Saving the form (which never sends the secret) keeps it; a value in the config is refused.
    put = env.client.put(f"/v1/sources/{sid}", headers=env.h(),
                         json={"config": {"git_url": url, **GIT, "priority": 2}})
    assert put.status_code == 200 and env.src("auto").config["webhook_secret"] == stored
    put = env.client.put(f"/v1/sources/{sid}", headers=env.h(),
                         json={"config": {"git_url": url, **GIT, "webhook_secret": "x"}})
    assert put.status_code == 422

    rot = env.post(f"/v1/sources/{sid}/webhook", {}).json()
    assert rot["rotated"] and rot["secret"] != secret
    gone = env.client.delete(f"/v1/sources/{sid}/webhook", headers=env.h())
    assert gone.json() == {"removed": True}
    assert "webhook_secret" not in env.src("auto").config
    assert env.client.delete(f"/v1/sources/{sid}/webhook", headers=env.h()).json() == {
        "removed": False}
    assert [a.action for a in env.actions("source.webhook")] == [
        "source.webhook.create", "source.webhook.rotate", "source.webhook.remove"]
    assert all(secret not in json.dumps(a.target) for a in env.actions("source"))


