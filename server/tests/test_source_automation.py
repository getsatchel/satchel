def test_schedule_due_not_due_and_unchanged_commit(env: Env, repo: tuple[str, str]) -> None:  # noqa: F811
    url, head = repo
    sid = git_source(env, url, sync_interval_hours=1)
    first = due(env)
    assert [(str(r.source_id), r.outcome, r.commit) for r in first] == [(sid, "synced", head)]
    src = env.src("auto")
    assert src.last_report["trigger"] == "schedule" and src.last_report["git_commit"] == head
    sync_audit = env.actions("source.sync")[-1].target
    assert sync_audit["trigger"] == "schedule" and sync_audit["git_commit"] == head

    assert due(env) == []  # synced just now: not due

    later = datetime.now(UTC) + timedelta(hours=2)
    [check] = due(env, later)
    assert check.outcome == "unchanged" and check.commit == head
    src = env.src("auto")
    assert src.last_synced_at == later and src.last_report["checked"]["commit"] == head
    assert src.last_report["trigger"] == "schedule"  # the sync report itself is kept
    assert len(env.actions("source.sync")) == 1  # a no-op check is not audited
    assert due(env, later + timedelta(minutes=30)) == []  # checked: waits a full interval

    new = commit(url, "second")
    [again] = due(env, later + timedelta(hours=2))
    assert again.outcome == "synced" and again.commit == new
    assert "checked" not in env.src("auto").last_report


