def github(env: Env, sid: str, payload: dict[str, Any], secret: str,  # noqa: F811
           event: str = "push", sig: str | None = None) -> Any:
    raw = json.dumps(payload).encode()
    mac = "sha256=" + hmac.new(secret.encode(), raw, hashlib.sha256).hexdigest()
    return env.client.post(f"/v1/hooks/sources/{sid}", content=raw, headers={
        "Content-Type": "application/json", "X-GitHub-Event": event,
        "X-GitHub-Delivery": "d-1", "X-Hub-Signature-256": sig or mac})


def gitlab(env: Env, sid: str, payload: dict[str, Any], token: str) -> Any:  # noqa: F811
    return env.client.post(f"/v1/hooks/sources/{sid}", json=payload, headers={
        "X-Gitlab-Event": "Push Hook", "X-Gitlab-Token": token})


PUSH_MAIN = {"ref": "refs/heads/main", "after": "a" * 40,
             "repository": {"default_branch": "main"}}


def test_github_push_syncs_after_responding(env: Env, repo: tuple[str, str]) -> None:  # noqa: F811
    url, head = repo
    sid = git_source(env, url)
    secret = env.post(f"/v1/sources/{sid}/webhook", {}).json()["secret"]

    ping = github(env, sid, {"zen": "hi"}, secret, event="ping")
    assert ping.status_code == 200 and ping.json()["status"] == "pong"

    r = github(env, sid, PUSH_MAIN, secret)
    assert r.status_code == 202 and r.json()["status"] == "queued"
    assert env.src("auto").last_synced_at is None  # queued, not run in the request
    assert env.drain() == 1
    src = env.src("auto")
    assert src.last_status == "ok" and src.last_report["trigger"] == "webhook"
    a = env.actions("source.sync")[-1].target
    assert a["trigger"] == "webhook" and a["provider"] == "github" and a["delivery"] == "d-1"
    assert a["ref"] == "refs/heads/main" and a["git_commit"] == head

    # A redelivery at the same commit does no work.
    assert github(env, sid, PUSH_MAIN, secret).status_code == 202
    env.drain()
    assert len(env.actions("source.sync")) == 1
    assert env.src("auto").last_report["checked"]["trigger"] == "webhook"


def test_quick_deliveries_coalesce_into_one_sync(env: Env, repo: tuple[str, str],  # noqa: F811
                                                 monkeypatch: pytest.MonkeyPatch) -> None:
    from satchel.sources import jobs as source_jobs

    url, _ = repo
    sid = git_source(env, url)
    secret = env.post(f"/v1/sources/{sid}/webhook", {}).json()["secret"]
    calls: list[uuid.UUID] = []

    def fake(source_id: uuid.UUID, **_k: Any) -> Any:
        calls.append(source_id)
        return AutoResult(source_id, "synced", "auto")

    monkeypatch.setattr(source_jobs, "run_sync", fake)
    first = github(env, sid, PUSH_MAIN, secret)
    assert first.status_code == 202 and first.json()["reason"] is None
    second = github(env, sid, PUSH_MAIN, secret)  # the first is still queued
    assert second.status_code == 202 and "already queued" in second.json()["reason"]
    assert env.drain() == 1 and calls == [uuid.UUID(sid)]

    # While a sync runs, one more delivery queues exactly one sync after it.
    with admin_session(engine=env.engine) as s:
        running = queue_sync(env.engine, env.ws_id, uuid.UUID(sid), trigger="webhook")[0]
        s.execute(update(Job).where(Job.id == running).values(
            status="running", locked_by="other", locked_until=func.now() + timedelta(minutes=5)))
    assert github(env, sid, PUSH_MAIN, secret).json()["reason"] is None
    assert "already queued" in github(env, sid, PUSH_MAIN, secret).json()["reason"]
    assert env.drain() == 1 and len(calls) == 2
    with admin_session(engine=env.engine) as s:
        s.execute(update(Job).where(Job.id == running).values(status="done"))


def test_lock_waiters_do_not_hold_connections(env: Env,  # noqa: F811
                                              monkeypatch: pytest.MonkeyPatch) -> None:
    import time
    from types import SimpleNamespace

    import satchel.sources.automation as auto

    sid = uuid.uuid4()
    pool: Any = env.engine.pool
    with sync_lock(env.engine, sid) as got:
        assert got
        held = pool.checkedout()
        seen: list[int] = []
        monkeypatch.setattr(auto, "time", SimpleNamespace(
            monotonic=time.monotonic, sleep=lambda _s: seen.append(pool.checkedout())))
        with sync_lock(env.engine, sid, wait_s=0.05, poll_s=0) as again:
            assert not again
        assert seen and all(n == held for n in seen)  # between attempts: nothing extra
        assert pool.checkedout() == held


def test_github_signatures_and_filters(env: Env, repo: tuple[str, str]) -> None:  # noqa: F811
    url, _ = repo
    sid = git_source(env, url)
    secret = env.post(f"/v1/sources/{sid}/webhook", {}).json()["secret"]
    unverified = {"detail": "missing or invalid webhook signature"}

    bad = github(env, sid, PUSH_MAIN, secret, sig="sha256=" + "0" * 64)
    assert bad.status_code == 401 and bad.json() == unverified
    assert github(env, sid, PUSH_MAIN, "wrong-secret").status_code == 401
    bare = env.client.post(f"/v1/hooks/sources/{sid}", json=PUSH_MAIN)
    assert bare.status_code == 401 and bare.json() == unverified
    # Unknown or malformed ids look exactly like a bad signature.
    for other in (str(uuid.uuid4()), "not-a-uuid"):
        r = github(env, other, PUSH_MAIN, secret)
        assert r.status_code == 401 and r.json() == unverified

    branch = github(env, sid, {**PUSH_MAIN, "ref": "refs/heads/feature"}, secret)
    assert branch.status_code == 200 and branch.json()["status"] == "ignored"
    assert "follows main" in branch.json()["reason"]
    issue = github(env, sid, {"action": "opened"}, secret, event="issues")
    assert issue.status_code == 200 and issue.json()["status"] == "ignored"
    assert env.src("auto").last_synced_at is None

    big = env.client.post(f"/v1/hooks/sources/{sid}", content=b"x" * ((1 << 20) + 1),
                          headers={"X-Gitlab-Token": secret})
    assert big.status_code == 413

    env.client.delete(f"/v1/sources/{sid}/webhook", headers=env.h())
    assert github(env, sid, PUSH_MAIN, secret).status_code == 401  # removed: refused


