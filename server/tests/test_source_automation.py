def test_cli_webhook_set_up_show_rotate_remove(env: Env, repo: tuple[str, str],  # noqa: F811
                                               monkeypatch: pytest.MonkeyPatch) -> None:
    from pydantic import SecretStr
    from typer.testing import CliRunner

    from satchel import settings as settings_mod
    from satchel.cli.main import app as cli
    from satchel.settings import Settings
    from satchel.store import db as dbmod
    from tests.test_settings_admin import KEY

    worker = dbmod.admin_engine_for(env.engine)
    monkeypatch.setattr(dbmod, "get_engine", lambda: env.engine)
    monkeypatch.setattr(dbmod, "get_admin_engine", lambda: worker)
    conf = Settings(dev_auth=True, encryption_key=SecretStr(KEY),
                    public_url="https://satchel.example.com")
    monkeypatch.setattr(settings_mod, "get_settings", lambda: conf)
    url, _ = repo
    sid = git_source(env, url, sync_interval_hours=6)
    run = CliRunner()
    base = ["-w", env.slug]

    first = run.invoke(cli, ["source", "webhook", "auto", *base])
    assert first.exit_code == 0, first.output
    hook = f"https://satchel.example.com/v1/hooks/sources/{sid}"
    assert "set up" in first.output and hook in first.output
    secret = first.output.split("secret: ")[1].split()[0]
    assert len(secret) >= 40 and is_sealed(env.src("auto").config["webhook_secret"])

    shown = run.invoke(cli, ["source", "webhook", "auto", *base])
    assert shown.exit_code == 0 and hook in shown.output and secret not in shown.output
    assert "--rotate" in shown.output

    lst = run.invoke(cli, ["source", "list", *base])
    assert "automatic: every 6h, next " in lst.output and "push webhook" in lst.output

    rot = run.invoke(cli, ["source", "webhook", "auto", *base, "--rotate"])
    assert rot.exit_code == 0 and "rotated" in rot.output and secret not in rot.output
    assert [a.action for a in env.actions("source.webhook")] == [
        "source.webhook.create", "source.webhook.rotate"]

    gone = run.invoke(cli, ["source", "webhook", "auto", *base, "--remove"])
    assert gone.exit_code == 0 and "removed" in gone.output
    assert "webhook_secret" not in env.src("auto").config
    again = run.invoke(cli, ["source", "webhook", "auto", *base, "--remove"])
    assert again.exit_code == 0 and "has no webhook" in again.output
    assert run.invoke(cli, ["source", "webhook", "nope", *base]).exit_code == 1
    both = run.invoke(cli, ["source", "webhook", "auto", *base, "--rotate", "--remove"])
    assert both.exit_code != 0


