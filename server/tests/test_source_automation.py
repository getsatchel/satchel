def test_failed_syncs_retry_with_backoff_up_to_the_interval(
        env: Env, repo: tuple[str, str]) -> None:  # noqa: F811
    url, _ = repo
    sid = git_source(env, url, sync_interval_hours=3, project="nope")
    t0 = datetime.now(UTC)
    assert due(env, t0)[0].outcome == "failed"
    # Retries 15, 30, 60, 120 minutes after each failure, then the 3 h interval caps it.
    for n, wait in enumerate([15, 30, 60, 120, 180, 180], start=1):
        src = env.src("auto")
        last = src.last_synced_at
        assert src.last_report["failures"] == n
        assert due(env, last + timedelta(minutes=wait - 1)) == [], (n, wait)
        listed = env.client.get("/v1/sources", headers=env.h()).json()
        [out] = [x for x in listed if x["id"] == sid]
        assert datetime.fromisoformat(out["next_sync_at"]) == last + timedelta(minutes=wait)
        # record_failure stamps the real clock, so step past it by the wait from "now".
        [r] = due(env, datetime.now(UTC) + timedelta(minutes=wait))
        assert r.outcome == "failed"

    # Fixing the config: the next due sync succeeds and the backoff resets.
    env.client.put(f"/v1/sources/{sid}", headers=env.h(), json={"config": {
        "git_url": url, "git_ref": "main", **GIT, "sync_interval_hours": 3}})
    [ok] = due(env, datetime.now(UTC) + timedelta(hours=3))
    assert ok.outcome == "synced"
    src = env.src("auto")
    assert "failures" not in src.last_report and src.last_status == "ok"
    listed = env.client.get("/v1/sources", headers=env.h()).json()
    [out] = [x for x in listed if x["id"] == sid]
    assert datetime.fromisoformat(out["next_sync_at"]) == src.last_synced_at + timedelta(hours=3)


