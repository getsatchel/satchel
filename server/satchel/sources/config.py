"""Source configuration: the host-level keys (publish mode, priority, connection) plus whatever
the adapter's ``config_model`` declares. Used by the CLI, ``satchel.config.yaml`` and the REST
API."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError
from satchel_adapter_sdk import FileInput, SourceFiles

from satchel.data.objstore import is_object_uri
from satchel.sources.dbt_build import DbtBuildError, check_config
from satchel.sources.registry import AdapterEntry

HOST_KEYS = ("publish", "priority", "connection", "git_url", "git_ref", "git_username", "git_token",
             "sync_interval_hours", "webhook_secret",
             # dbt sources from git: build the manifest with dbt parse (satchel.sources.dbt_build)
             "dbt_project_dir", "dbt_skip_deps", "dbt_vars", "dbt_target_schema",
             "dbt_target_name")
# Generated by the server (Push webhook on the Sources page), sealed, never set from a config.
WEBHOOK_KEY = "webhook_secret"
MIN_INTERVAL_H, MAX_INTERVAL_H = 1, 168
# folders an input of ``multiple=True`` never descends into
SKIP_DIRS = {"node_modules", "__pycache__", "venv", "dist", "build", "target", "logs"}
MAX_FILES = 5000
MAX_BYTES = 64 * 1024 * 1024


class SourceConfigError(ValueError):
    pass


class HostSettings(BaseModel):
    """Keys every source accepts, whatever the adapter."""

    model_config = ConfigDict(extra="ignore")

    publish: Literal["auto", "preview"] = "auto"
    priority: int = Field(
        default=0,
        description="Lower number wins when sources describe the same table (hand-written "
        "docs count as 0 and win ties)",
    )
    connection: str | None = Field(default=None, description="Warehouse connection name")
    # Read file inputs as paths inside this repository (satchel.sources.git).
    git_url: str | None = Field(default=None, description="https:// git repository")
    git_ref: str | None = Field(default=None, description="Branch, tag or commit")
    git_username: str | None = None
    git_token: str | None = None
    # Scheduled sync (satchel.sources.automation): the worker syncs the source when its last
    # sync is older than this. Needs a stored location for every required file input.
    sync_interval_hours: int | None = Field(
        default=None, ge=MIN_INTERVAL_H, le=MAX_INTERVAL_H,
        description="Sync automatically every N hours (1-168); unset = only on request")
    # dbt + git: build manifest.json from this project folder with `dbt parse` instead of
    # reading a committed one (satchel.sources.dbt_build).
    dbt_project_dir: str | None = Field(default=None, description="dbt project folder in the "
                                        "repository (. for the root)")
    dbt_skip_deps: bool = Field(default=False, description="Skip dbt deps (packages vendored "
                                "in dbt_packages/)")
    dbt_vars: dict[str, str | int | float | bool | None] | None = Field(
        default=None, description="Non-secret --vars for dbt parse")
    dbt_target_schema: str | None = Field(default=None, description="target.schema of the "
                                          "production target")
    dbt_target_name: str | None = Field(default=None, description="target.name (default prod)")


def split_config(config: dict[str, Any]) -> tuple[HostSettings, dict[str, Any]]:
    host_raw = {k: config[k] for k in HOST_KEYS if config.get(k) is not None}
    try:
        host = HostSettings.model_validate(host_raw)
    except ValidationError as e:
        raise SourceConfigError(_fmt(e)) from None
    return host, {k: v for k, v in config.items() if k not in HOST_KEYS}


def validate_config(entry: AdapterEntry, config: dict[str, Any]) -> tuple[HostSettings, BaseModel]:
    host, adapter_cfg = split_config(config)
    try:
        cfg = entry.info.config_model.model_validate(adapter_cfg)
    except ValidationError as e:
        raise SourceConfigError(_fmt(e)) from None
    try:
        check_config(entry.kind, {**config, **host.model_dump()})
    except DbtBuildError as e:
        raise SourceConfigError(str(e)) from None
    return host, cfg


def config_with_defaults(entry: AdapterEntry, config: dict[str, Any]) -> dict[str, Any]:
    """The config to store: validated, host keys first, adapter keys with ``None`` dropped."""
    host, cfg = validate_config(entry, config)
    out: dict[str, Any] = {"publish": host.publish, "priority": host.priority}
    if host.connection:
        out["connection"] = host.connection
    for k in ("git_url", "git_ref", "git_username", "git_token", "sync_interval_hours",
              "dbt_project_dir", "dbt_skip_deps", "dbt_vars", "dbt_target_schema",
              "dbt_target_name"):
        if getattr(host, k):
            out[k] = getattr(host, k)
    out.update({k: v for k, v in cfg.model_dump(mode="json").items() if v is not None})
    return out


def unstored_inputs(entry: AdapterEntry, stored: dict[str, Any]) -> list[str]:
    """Required file inputs with no stored location (uploaded on each sync). A source with any
    cannot sync on its own (schedule, push webhook)."""
    # dbt from git with a project folder: dbt parse builds the manifests on every sync.
    built = ({"manifest", "semantic_manifest"}
             if stored.get("git_url") and stored.get("dbt_project_dir") else set())
    return [f.name for f in entry.info.file_inputs
            if f.required and f.name not in built and not stored.get(f.name)]


def check_automatable(entry: AdapterEntry, stored: dict[str, Any], what: str) -> None:
    missing = unstored_inputs(entry, stored)
    if missing:
        raise SourceConfigError(
            f"{what} needs a stored location for {', '.join(missing)}: set a path in the git "
            "repository or an s3:// / gs:// location (a source whose files are uploaded on "
            "each sync can only be synced by whoever uploads them, e.g. CI)")


def _read_tree(fi: FileInput, root: Path) -> dict[str, bytes]:
    """The files of a ``multiple`` input as ``{'<name>/<relative path>': bytes}``. ``root`` is a
    file or a folder; folders are walked in sorted order, skipping dot folders, dependency and
    build folders and files whose suffix is not in ``fi.extensions``."""
    root.stat()  # a missing path is an OSError, reported with the path
    if root.is_file():
        return {f"{fi.name}/{root.name}": root.read_bytes()}
    wanted = {e.lower() for e in fi.extensions}
    out: dict[str, bytes] = {}
    total = 0
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if any(part.startswith(".") or part in SKIP_DIRS for part in rel.parts[:-1]):
            continue
        if not p.is_file() or rel.name.startswith("."):
            continue
        if wanted and p.suffix.lower() not in wanted:
            continue
        data = p.read_bytes()
        total += len(data)
        if len(out) >= MAX_FILES or total > MAX_BYTES:
            raise SourceConfigError(
                f"{fi.name} at {root} is too large: more than {MAX_FILES} files or "
                f"{MAX_BYTES >> 20} MB. Point it at the model folder only."
            )
        out[f"{fi.name}/{rel.as_posix()}"] = data
    return out


def _wanted(fi: FileInput, rel: str) -> bool:
    parts = rel.split("/")
    if any(part.startswith(".") or part in SKIP_DIRS for part in parts[:-1]):
        return False
    if not parts[-1] or parts[-1].startswith("."):
        return False
    wanted = {e.lower() for e in fi.extensions}
    return not wanted or any(parts[-1].lower().endswith(e) for e in wanted)


def _read_object(fi: FileInput, uri: str) -> dict[str, bytes]:
    """An input stored in GCS or S3: one object, or (``multiple`` inputs) every object under a
    prefix, filtered like a local folder. Read with the server's own cloud identity."""
    from satchel.data.objstore import describe, open_bucket, split_uri

    scheme, bucket_name, key = split_uri(uri)
    bucket = open_bucket(scheme, bucket_name)
    where = f"{describe(scheme)} {uri}"
    size = bucket.size(key) if key and not key.endswith("/") else None
    if size is not None:
        if size > MAX_BYTES:
            raise SourceConfigError(f"{fi.name} at {where} is larger than {MAX_BYTES >> 20} MB")
        name = f"{fi.name}/{key.rsplit('/', 1)[-1]}" if fi.multiple else fi.name
        return {name: bucket.read_range(key, 0, size)}
    if not fi.multiple:
        raise SourceConfigError(f"cannot read {fi.name}: no object at {where}")
    prefix = key.rstrip("/") + "/" if key else ""
    listed = bucket.list(prefix, MAX_FILES + 1)
    out: dict[str, bytes] = {}
    total = 0
    for name, n in listed:
        rel = name[len(prefix):]
        if not _wanted(fi, rel):
            continue
        total += n
        if len(out) >= MAX_FILES or total > MAX_BYTES:
            raise SourceConfigError(
                f"{fi.name} at {where} is too large: more than {MAX_FILES} files or "
                f"{MAX_BYTES >> 20} MB. Point it at the model folder only."
            )
        out[f"{fi.name}/{rel}"] = bucket.read_range(name, 0, n)
    if not out:
        raise SourceConfigError(f"cannot read {fi.name}: no matching objects under {where}")
    return out


def read_files(
    entry: AdapterEntry,
    cfg: BaseModel,
    uploads: dict[str, bytes] | None = None,
    base_dir: Path | None = None,
    repo_root: Path | None = None,
) -> SourceFiles:
    """Load the adapter's input files: uploads win, else the path in the config. An input of
    ``multiple=True`` may be a folder; its files are named ``<input>/<relative path>`` (uploads
    use the same names). With ``repo_root`` (a git checkout), paths are inside the repository."""
    data: dict[str, bytes] = {}
    for fi in entry.info.file_inputs:
        if uploads:
            if fi.multiple:
                sent = {k: v for k, v in uploads.items() if k.startswith(f"{fi.name}/")}
                if sent:
                    data.update(sent)
                    continue
            if fi.name in uploads:
                data[fi.name if not fi.multiple else f"{fi.name}/{fi.name}"] = uploads[fi.name]
                continue
        path = getattr(cfg, fi.name, None)
        if path and is_object_uri(str(path)):
            try:
                data.update(_read_object(fi, str(path)))
            except SourceConfigError:
                raise
            except Exception as e:  # noqa: BLE001 - cloud SDK errors (auth, network)
                raise SourceConfigError(
                    f"cannot read {fi.name} at {path}: {type(e).__name__}: {e}") from None
        elif path:
            if repo_root is not None:
                from satchel.sources.git import GitSourceError, inside

                try:
                    p = inside(repo_root, str(path))
                except GitSourceError as e:
                    raise SourceConfigError(f"{fi.name}: {e}") from None
            else:
                p = Path(str(path)).expanduser()
                if not p.is_absolute() and base_dir is not None:
                    p = base_dir / p
            try:
                if fi.multiple:
                    data.update(_read_tree(fi, p))
                else:
                    data[fi.name] = p.read_bytes()
            except OSError as e:
                where = f"{path} in the repository" if repo_root is not None else str(p)
                raise SourceConfigError(f"cannot read {fi.name} at {where}: {e.strerror}") from None
        elif fi.required:
            raise SourceConfigError(f"{fi.name} is required ({fi.description or 'input file'})")
    missing = [
        f.name for f in entry.info.file_inputs
        if f.required and not any(k == f.name or k.startswith(f"{f.name}/") for k in data)
    ]
    if missing:
        raise SourceConfigError(f"missing required input file(s): {', '.join(missing)}")
    return SourceFiles(data)


def _fmt(e: ValidationError) -> str:
    return "; ".join(
        f"{'.'.join(str(p) for p in err['loc']) or 'config'}: {err['msg']}" for err in e.errors()
    )
